<h1>About the Library</h1>

<h2>🌸 What is the Library?</h2>

<p>
The SIB Paguokon Rebana Dance Library is a digital library developed to preserve,
organize, and provide easy access to Rebana dance learning resources. The system
stores instructional videos, music, documents, and other educational materials
to support learning and preserve the cultural heritage of the SIB Paguokon community.
</p>

<h2>💕 Who Manages It?</h2>

<p>
The library system is managed by the administrators of the SIB Paguokon Rebana Dance
Library. Administrators are responsible for maintaining the collection, uploading
learning materials, and managing user access to ensure that the resources remain
organized and up to date.
</p>

<h2>🎯 Goals of the System</h2>

<ul>
    <li>Preserve the cultural heritage of the Rebana dance.</li>
    <li>Provide centralized access to learning resources.</li>
    <li>Support students, instructors, and community members in learning the dance.</li>
    <li>Improve the management of digital library materials.</li>
</ul>

